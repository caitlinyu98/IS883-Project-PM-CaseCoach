import streamlit as st
from prompts import QUESTIONS, FOLLOWUP_AFTER
from interviewer import generate_followup
from feedback import generate_report, MIN_WORDS, TAXONOMY
from llm import LLMError

MAX_REQUESTS = 12  # per session request cap (free tier protection)

st.set_page_config(page_title="PM CaseCoach", page_icon="🎤")
st.title("PM CaseCoach")
st.caption("Practice B2B product manager interview questions and get a feedback report.")
st.warning("Output is generated by a language model and may be wrong. It is not professional career advice. "
           "Do not enter personal or confidential information. Free tier Gemini inputs may be used by Google.")

defaults = {"started": False, "q_idx": 0, "phase": "answer", "transcript": [],
            "follow_up": "", "requests": 0, "result": None}
for k, v in defaults.items():
    st.session_state.setdefault(k, v)
S = st.session_state


def use_request():
    if S.requests >= MAX_REQUESTS:
        st.error("Session request limit reached. Please reload the page to start a new session.")
        return False
    S.requests += 1
    return True


def restart():
    for k, v in defaults.items():
        S[k] = v if not isinstance(v, list) else []


def too_short(text):
    return len(text.split()) < MIN_WORDS


if not S.started:
    st.write(f"{len(QUESTIONS)} questions, up to {len(FOLLOWUP_AFTER)} follow ups, then a report.")
    if st.button("Start interview"):
        S.started = True
        st.rerun()

elif S.result is not None:
    res = S.result
    report = res["report"]
    st.subheader("Your feedback report")
    if report is None:
        st.error("The feedback could not be formatted this time. Please try the report again.")
    else:
        st.write(report["overall_summary"])
        if report["strengths"]:
            st.markdown("**Strengths**")
            for s in report["strengths"]:
                st.markdown(f"- {s}")
        st.markdown("**Weaknesses**")
        if not report["weaknesses"]:
            st.markdown("- None flagged.")
        for w in report["weaknesses"]:
            st.markdown(f"- **{TAXONOMY[w['tag']]}**: {w['evidence']}  \n  Fix: {w['fix']}")
        if report["next_steps"]:
            st.markdown("**Next steps**")
            for s in report["next_steps"]:
                st.markdown(f"- {s}")
        if res["meta"].get("retrieval_failed"):
            st.caption("Note: rubric retrieval was unavailable, so this report used the base prompt only.")
    if st.button("Start over"):
        restart()
        st.rerun()

elif S.phase == "ready":
    st.success("Interview complete.")
    if st.button("Get my feedback report"):
        if use_request():
            try:
                S.result = generate_report(S.transcript)
                st.rerun()
            except LLMError as e:
                st.error("The model service is unavailable right now. Please try again in a minute.")
                st.caption(f"Debug: {e}")
                print("LLMError:", repr(e))

else:
    idx = S.q_idx
    q = QUESTIONS[idx]
    st.progress(idx / len(QUESTIONS), text=f"Question {idx + 1} of {len(QUESTIONS)}")
    st.markdown(f"**{q}**")

    if S.phase == "followup":
        st.info(f"Follow up: {S.follow_up}")

    with st.form(key=f"form_{idx}_{S.phase}"):
        ans = st.text_area("Your answer", height=200)
        submitted = st.form_submit_button("Submit")

    if submitted:
        if not ans.strip():
            st.error("Please write an answer first.")
        elif too_short(ans):
            st.error("That is too short to assess. Please write a fuller answer.")
        elif S.phase == "answer":
            if use_request():
                try:
                    r = generate_followup(q, ans)
                except LLMError as e:
                    st.error("The model service is unavailable right now. Please try again in a minute.")
                    st.caption(f"Debug: {e}")
                    print("LLMError:", repr(e))
                else:
                    if not r["in_scope"]:
                        st.warning("That does not look like an answer to this question. Please try again.")
                    else:
                        S.transcript.append({"question": q, "answer": ans})
                        if idx in FOLLOWUP_AFTER:
                            S.follow_up = r["follow_up"]
                            S.transcript[-1]["follow_up"] = r["follow_up"]
                            S.phase = "followup"
                        else:
                            S.q_idx += 1
                            S.phase = "answer" if S.q_idx < len(QUESTIONS) else "ready"
                        st.rerun()
        else:  # follow up answer: no model call needed
            S.transcript[-1]["follow_up_answer"] = ans
            S.q_idx += 1
            S.phase = "answer" if S.q_idx < len(QUESTIONS) else "ready"
            st.rerun()
