import streamlit as st

# ---------- Config ----------
MODEL = "gemini-2.5-flash-lite"  # confirm the current free tier model name in Google AI Studio
MAX_REQUESTS_PER_SESSION = 10    # per session cap required by directives section 3.2

st.set_page_config(page_title="PM Case Coach", page_icon="🎯")

# ---------- Session state ----------
if "request_count" not in st.session_state:
    st.session_state.request_count = 0


def can_call_model() -> bool:
    """Return True if this session still has requests left."""
    return st.session_state.request_count < MAX_REQUESTS_PER_SESSION


def get_client():
    """Create the Gemini client. The key lives in Streamlit Secrets, never in the repo."""
    from google import genai
    return genai.Client(api_key=st.secrets["MyGeminiKey"])


# ---------- UI ----------
st.title("PM Case Coach")
st.write("Hello! This is a placeholder. The interview practice app will live here.")
st.caption(
    "Output is generated by a language model and may be wrong. "
    "It is not professional career or legal advice."
)

st.sidebar.write(f"Requests used: {st.session_state.request_count} / {MAX_REQUESTS_PER_SESSION}")

if st.button("Test Gemini connection"):
    if not can_call_model():
        st.warning("Session request limit reached. Please refresh to start a new session.")
    else:
        try:
            st.session_state.request_count += 1
            client = get_client()
            reply = client.models.generate_content(model=MODEL, contents="Say hello in five words.")
            st.success(reply.text)
        except KeyError:
            st.error("API key not found. Add MyGeminiKey in the app's Secrets settings.")
        except Exception as e:
            st.error(f"The model call failed. Please try again later. ({type(e).__name__})")
