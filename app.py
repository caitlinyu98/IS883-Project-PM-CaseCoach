
# Failure paths: empty or too short answer (rule, no model call), off topic answer
# (model sets in_scope = false), API error (friendly message), report that does not
# parse (retry button), and the per session request cap.
import html
import json
import os
import streamlit as st
from prompts import FOLLOWUP_AFTER
from question_bank import pick_interview
from interviewer import generate_followup
from feedback import generate_report, MIN_WORDS, TAXONOMY
from llm import LLMError

MAX_REQUESTS = 15   # model calls per browser session (directives §3.2); Start over reloads the session, which resets it
NUM_QUESTIONS = 4
DEMO_PATH = os.path.join(os.path.dirname(__file__), "data", "sample_transcript.json")
API_DOWN = "The model service is unavailable right now. Please try again in a minute."

st.set_page_config(page_title="Product Manager Case Coach", page_icon="🎤")
st.title("Product Manager Case Coach")
st.caption("Practice a B2B SaaS product manager interview and get a feedback report.")
st.warning("Output is generated by a language model and may be wrong. It is not professional career advice. "
           "Do not enter personal or confidential information. Free tier Gemini inputs may be used by Google.")

# ---- session state ----
S = st.session_state
INTERVIEW_DEFAULTS = {"started": False, "demo": False, "questions": [], "q_idx": 0, "phase": "answer",
                      "transcript": [], "messages": [], "result": None, "log": []}
for k, v in INTERVIEW_DEFAULTS.items():
    S.setdefault(k, [] if isinstance(v, list) else v)
S.setdefault("requests", 0)  # model calls used; cleared with everything else when Start over reloads the session


def reset_interview():
    for k, v in INTERVIEW_DEFAULTS.items():
        S[k] = [] if isinstance(v, list) else v


def use_request(count=1):
    if S.requests + count > MAX_REQUESTS:
        st.error("You reached the practice limit for this session. Please come back later.")
        return False
    S.requests += count
    return True


def say(role, text):
    S.messages.append((role, text))


def ask_current_question():
    q = S.questions[S.q_idx]
    say("assistant", f"**Question {S.q_idx + 1} of {len(S.questions)}.** {q['question']}")


def next_question():
    S.q_idx += 1
    if S.q_idx < len(S.questions):
        S.phase = "answer"
        ask_current_question()
    else:
        end_interview()


def end_interview():
    S.phase = "ready"
    say("assistant", "That's the end of the interview. Click **Get my feedback report** below.")


def start_interview():
    reset_interview()
    S.started = True
    S.questions = pick_interview(NUM_QUESTIONS)
    say("assistant", "Thanks for joining. I'll ask you B2B product questions one at a time, "
                     "with a follow up after some of them. Answer as you would in a real interview.")
    ask_current_question()


def load_demo():
    reset_interview()
    with open(DEMO_PATH, encoding="utf-8") as f:
        S.transcript = json.load(f)
    S.started, S.demo, S.phase = True, True, "ready"
    for t in S.transcript:
        say("assistant", t["question"])
        say("user", t["answer"])
        if t.get("follow_up"):
            say("assistant", t["follow_up"])
            say("user", t.get("follow_up_answer", ""))
    say("assistant", "This is a demo transcript. Click **Get my feedback report** below to see its report.")


def handle_answer(ans):
    """One typed answer: rule checks first, then (for main questions) the follow up model call."""
    if not ans.strip():
        st.warning("Your answer is empty. Type something to continue.")
        return
    if len(ans.split()) < MIN_WORDS:
        st.warning("That is too short to assess. Please write a fuller answer.")
        return
    if S.phase == "followup":  # a follow up answer needs no model call
        say("user", ans)
        S.transcript[-1]["follow_up_answer"] = ans
        next_question()
        st.rerun()
    q = S.questions[S.q_idx]
    if not use_request():
        return
    with st.status("Contacting Gemini...", expanded=True) as model_status:
        try:
            r = generate_followup(
                q["question"],
                ans,
                on_model_status=lambda message: model_status.update(
                    label=message, state="running", expanded=True
                ),
            )
        except LLMError as e:
            print("LLMError:", repr(e))  # real error goes to the logs, the user sees a friendly message
            model_status.update(state="error", expanded=True)
            st.error(API_DOWN)
            return
        model_status.update(state="complete", expanded=False)
    S.log.append(f"follow up for {q['id']}: in_scope={r['in_scope']}, fallback_used={r['fallback_used']}")
    if not r["in_scope"]:
        st.warning("That does not look like an answer to this question. Please try again.")
        return
    say("user", ans)
    S.transcript.append({"question": q["question"], "answer": ans})
    if S.q_idx in FOLLOWUP_AFTER:
        S.transcript[-1]["follow_up"] = r["follow_up"]
        S.phase = "followup"
        say("assistant", r["follow_up"])
    else:
        next_question()
    st.rerun()


def _box(title, items_html, color, bg, full=False):
    # colored card: strong border and title in `color`, soft background `bg`
    body = "".join(f"<li style='margin-bottom:6px'>{i}</li>" for i in items_html) or "<li>None flagged.</li>"
    return (
        f"<div style='border:2px solid {color};background:{bg};border-radius:10px;"
        f"padding:12px 16px;height:100%;color:#1f1f1f;{'margin-top:12px;' if full else ''}'>"
        f"<div style='color:{color};font-weight:700;font-size:1.1rem;margin-bottom:6px'>{title}</div>"
        f"<ul style='margin:0;padding-left:20px'>{body}</ul></div>"
    )


def show_report(res):
    report = res["report"]
    esc = html.escape
    with st.chat_message("assistant"):
        # no default heading margin, so the title lines up with the avatar
        st.markdown("<h3 style='margin:0;padding:0;line-height:2rem'>Your feedback report</h3>",
                    unsafe_allow_html=True)
        score = report.get("overall_score")
        if score is not None:
            color = "#d32f2f" if score <= 4 else "#f57c00" if score <= 6 else "#2e7d32"
            st.markdown(
                f"<div style='font-size:2.5rem;font-weight:700;margin:8px 0'>"
                f"Score: <span style='color:{color}'>{score} / 10</span></div>",
                unsafe_allow_html=True,
            )
        st.write(report["overall_summary"])

        strengths = [esc(s) for s in report["strengths"]]
        weaknesses = [
            f"<b>{esc(TAXONOMY[w['tag']])}</b>: {esc(w['evidence'])}<br><i>Fix:</i> {esc(w['fix'])}"
            for w in report["weaknesses"]
        ]
        next_steps = [esc(s) for s in report["next_steps"]]

        st.markdown(
            "<div style='display:grid;grid-template-columns:1fr 1fr;gap:12px'>"
            + _box("Strengths", strengths, "#2e7d32", "#e8f5e9")
            + _box("What to work on", weaknesses, "#c62828", "#ffebee")
            + "</div>",
            unsafe_allow_html=True,
        )
        if next_steps:
            st.markdown(_box("Next steps", next_steps, "#b28704", "#fff8e1", full=True),
                        unsafe_allow_html=True)
        if res["meta"].get("retrieval_failed"):
            st.caption("Note: rubric retrieval was unavailable, so this report used the base prompt only.")


# ---- sidebar: setup and controls ----
with st.sidebar:
    st.selectbox("Company type", ["B2B SaaS"], disabled=True)
    st.selectbox("Role level", ["MBA PM intern"], disabled=True)
    # --- Caitlin: Start over reloads the whole session (written with Claude Code as coding assistant) ---
    if st.button("Start over" if S.started else "Start interview", type="primary", use_container_width=True):
        if S.started:
            S.clear()  # wipe the interview and the model call counter; the rerun rebuilds a fresh session
        else:
            start_interview()
        st.rerun()
    can_end = S.started and S.phase in ("answer", "followup") and len(S.transcript) > 0
    if st.button("End interview and get feedback", disabled=not can_end, use_container_width=True):
        end_interview()
        st.rerun()
    if st.button("Try a demo transcript", use_container_width=True):
        load_demo()
        st.rerun()
    st.caption(f"Model calls used this session: {S.requests} of {MAX_REQUESTS}")
    # Shows where the model calls fire, for development and the Q&A demo. Remove or keep before the tag.
    with st.expander("Behind the Scenes"):
        st.write(S.log or "Nothing yet.")

# ---- the conversation ----
if not S.started:
    st.info("Click **Start interview** in the sidebar, or **Try a demo transcript** to see a sample report.")

for role, text in S.messages:
    st.chat_message(role).markdown(text)

# ---- the feedback report ----
if S.started and S.phase == "ready":
    if S.result is None:
        if st.button("Get my feedback report", type="primary") and use_request(2):
            with st.status("Preparing your feedback report...", expanded=True) as model_status:
                try:
                    S.result = generate_report(
                        S.transcript,
                        on_model_status=lambda message: model_status.update(
                            label=message, state="running", expanded=True
                        ),
                    )
                except LLMError as e:
                    print("LLMError:", repr(e))
                    model_status.update(state="error", expanded=True)
                    st.error(API_DOWN)
                else:
                    model_status.update(state="complete", expanded=False)
            if S.result is not None:
                m = S.result["meta"]
                S.log.append(f"report: parse_ok={m['parse_ok']}, rule_based={m['rule_based']}, "
                             f"retrieval_used={m['retrieval_used']}, retrieved_tags={m['retrieved_tags']}")
                for call in m["tool_calls"]:
                    S.log.append(
                        f"tool: {call['name']}({call['argument']}) -> {call['result_id']}"
                    )
                st.rerun()
    elif S.result["report"] is None:
        st.error("The feedback could not be formatted this time. Your answers are saved.")
        if st.button("Try the report again"):  # costs one more request against the cap
            S.result = None
            st.rerun()
    else:
        show_report(S.result)

# ---- answer box ----
if S.started and S.phase in ("answer", "followup"):
    answer = st.chat_input("Type your answer")
    if answer is not None:
        handle_answer(answer)
